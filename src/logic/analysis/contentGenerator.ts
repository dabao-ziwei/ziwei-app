import { RawAnalysisResult } from './types';

export const generateAnalysisContent = (result: RawAnalysisResult): string => {
    // 這裡實作固定文案模板，確保同一標籤產出穩定文字
    const { line, riskTags } = result;
    
    if (riskTags.includes("年度平穩發展")) {
        return "今年此面向的能量波動較小，適合維持現有的節奏。這是一個積累與沉澱的好時機，建議您專注於長期的目標，不必急於在短時間內尋求巨大的變革。";
    }

    if (line === '夫官線') {
        return "本年度在職業發展與情感連結上，將會是您需要多花心力去平衡的重點。這並非意味著挫折，而是一個提醒您檢視內心真正需求、並與伴侶或工作夥伴重新建立溝通默契的成長課題。";
    }
    
    if (line === '命遷線') {
        return "今年的外在環境可能會帶來一些意料之外的變動。這是一個邀請您重新審視自我定位的契機。透過對環境變化的觀察，您能發現更強大的內在韌性，建議在做決策前多給自己一些留白的時間。";
    }

    if (line === '財福線') {
        return "關於資源的調度與物質的運用，今年建議採取更為審慎、保守的策略。內心的價值感或許會受到一些挑戰，提醒您區分『需要』與『想要』，學會與現有的資源共處，會帶給您更多的安全感。";
    }

    return "這是一個需要您細心體會、從中學習平衡的年度課題。";
};